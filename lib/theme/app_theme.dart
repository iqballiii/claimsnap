        letterSpacing: 0.5,
      ),
    );
  }

  /// Additional helper methods for specific use cases

  /// Get monospace text style for data display (claim numbers, amounts)
  static TextStyle getDataTextStyle({
    required bool isLight,
    double fontSize = 14,
    FontWeight fontWeight = FontWeight.w400,
  }) {
    final Color textColor = isLight ? textPrimaryLight : textPrimaryDark;
    return GoogleFonts.jetBrainsMono(
      fontSize: fontSize,
      fontWeight: fontWeight,
      color: textColor,
      letterSpacing: 0.5,
    );
  }

  /// Get status color based on claim status
  static Color getStatusColor(String status) {
    switch (status.toLowerCase()) {
      case 'approved':
      case 'completed':
      case 'success':
        return successLight;
      case 'pending':
      case 'in_progress':
      case 'processing':
        return warningLight;
      case 'rejected':
      case 'failed':
      case 'error':
        return errorLight;
      case 'alert':
      case 'urgent':
        return accentLight;
      default:
        return textSecondaryLight;
    }
  }

  /// Get gradient for primary action buttons
  static LinearGradient getPrimaryGradient({bool isLight = true}) {
    if (isLight) {
      return LinearGradient(
        colors: [primaryLight, primaryVariantLight],
        begin: Alignment.topLeft,
        end: Alignment.bottomRight,
      );
    } else {
      return LinearGradient(
        colors: [primaryDark, primaryVariantDark],
        begin: Alignment.topLeft,
        end: Alignment.bottomRight,
      );
    }
  }

  /// Get subtle status gradient for status indicators
  static LinearGradient getStatusGradient(String status) {
    final Color statusColor = getStatusColor(status);
    return LinearGradient(
      colors: [
        statusColor.withValues(alpha: 0.1),
        statusColor.withValues(alpha: 0.05),
      ],
      begin: Alignment.topLeft,
      end: Alignment.bottomRight,
    );
  }
